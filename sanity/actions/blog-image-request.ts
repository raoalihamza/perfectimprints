/**
 * What the blog Studio buttons send to /api/sanity/generate-blog-image and
 * what they patch with its answer (AUTO-202, AUTO-220). PURE and shared, so
 * the "Generate header image" button, the two instruction buttons and
 * Generate / Regenerate Blog with AI cannot build the request or read the
 * outcome two different ways. No React, no Sanity, no server imports (the
 * Studio bundle takes it).
 */
import { collectBlogProductSkus } from '../../lib/blog/collect-strip-skus';
// Pure (no Sanity, no fs, no network): the one place the reasons are worded.
import { headerImageWhy } from '../../lib/blog-automation/header-image';
import { MAX_HEADER_EDITS_IN_A_ROW, cleanInstruction, editCountOf, rungOf } from '../../lib/blog-automation/header-brief';

interface ImageRef {
  asset?: { _ref?: unknown } | null;
}

export interface BlogImageDoc {
  title?: unknown;
  slug?: { current?: unknown } | null;
  body?: unknown;
  headerImage?: {
    asset?: { _ref?: unknown } | null;
    titleOnImage?: unknown;
    /** AUTO-220: the rung of the ladder the picture was drawn on. */
    ladderRung?: unknown;
    /** AUTO-220: changes in a row this picture carries. */
    editCount?: unknown;
    /** AUTO-220: the picture without the P! mark. */
    unmarkedImage?: ImageRef | null;
    /** AUTO-209 to AUTO-212 (no longer written): the old composite's copy without the title. Read only so it is removed with the picture it belongs to. */
    untitledImage?: ImageRef | null;
  } | null;
  externalHeaderImage?: { url?: unknown } | null;
  headerImageSource?: unknown;
  /** AUTO-220: Patrick's own instruction for the header image. */
  headerImageInstruction?: unknown;
  aiTopicKeywords?: unknown;
  sourceTopic?: { query?: unknown } | null;
  relatedCategorySlugs?: unknown;
}

/** The route's answer, the part the buttons read. */
export interface ImageOutcome {
  kind: 'asset' | 'url' | 'none';
  source?: 'ai' | 'library' | 'product';
  image?: {
    _type: 'image';
    asset: { _type: 'reference'; _ref: string };
    alt?: string;
    /** Set when the picture carries the post's title. */
    titleOnImage?: string;
    ladderRung?: number;
    editCount?: number;
    unmarkedImage?: { _type: 'image'; asset: { _type: 'reference'; _ref: string } };
  };
  url?: string;
  alt?: string;
  notes?: string[];
  usage?: { capUsed?: number; cap?: number; attempts?: number; mode?: string; rung?: number };
}

export interface ImageResponse {
  ok?: boolean;
  outcome?: ImageOutcome;
  /** The whole line: "Header image: <what>. <why>". */
  summary?: string;
  /** What the image is, bare: "generated by the AI from the post's product photos, with the post's title on it". */
  what?: string;
  /** Why, as sentences, each reason said once; empty when there is nothing to say (AUTO-204). */
  why?: string;
  error?: string;
}

/**
 * The reasons behind an outcome, as sentences (AUTO-204). The route's own
 * wording when it sent one; otherwise the notes, sentence by sentence. A
 * dialog prints this ONCE.
 */
export function imageWhy(data: ImageResponse | undefined): string {
  if (typeof data?.why === 'string') return data.why.trim();
  return headerImageWhy({ notes: data?.outcome?.notes ?? [] });
}

/**
 * What the image is and why, with NO "Header image:" label, for a dialog
 * line that already carries the label ("Filled in: Header image. ...").
 */
export function imageDetail(data: ImageResponse | undefined): string {
  const what = (data?.what ?? '').trim();
  const why = imageWhy(data);
  const first = what ? `${what.charAt(0).toUpperCase()}${what.slice(1)}.` : '';
  return [first, why].filter(Boolean).join(' ');
}

function strings(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((v): v is string => typeof v === 'string' && v.trim().length > 0).map((v) => v.trim()) : [];
}

function refOf(image: ImageRef | null | undefined): string | null {
  const ref = image?.asset?._ref;
  return typeof ref === 'string' && ref ? ref : null;
}

/** The current header image as one comparable string: the asset ref, the hot link, or empty. */
export function headerImageSignature(doc: BlogImageDoc | null | undefined): string {
  const ref = doc?.headerImage?.asset?._ref;
  if (typeof ref === 'string' && ref) return `asset:${ref}`;
  const url = doc?.externalHeaderImage?.url;
  if (typeof url === 'string' && url.trim()) return `url:${url.trim()}`;
  return '';
}

/** The uploaded header image's asset id, or null (a hot link or no image). AUTO-207: what a replace takes off the post. */
export function headerAssetRefOf(doc: BlogImageDoc | null | undefined): string | null {
  return refOf(doc?.headerImage);
}

/** The asset id of a GENERATED picture in an answer, or null (a library picture, a product photo, nothing). */
export function generatedAssetRefOf(outcome: ImageOutcome | undefined): string | null {
  return outcome?.kind === 'asset' && outcome.source === 'ai' && typeof outcome.image?.asset?._ref === 'string' ? outcome.image.asset._ref : null;
}

/**
 * The copies kept BESIDE the post's header picture: the picture without the
 * P! mark (AUTO-220) and, on a picture made before it, the old copy without
 * the title (AUTO-209). They go wherever the picture goes, through the same
 * guarded removal rule (ours, and referenced by nothing). Never the header
 * asset itself, each id once.
 */
export function copyAssetRefsOf(doc: BlogImageDoc | null | undefined): string[] {
  const header = headerAssetRefOf(doc);
  const out: string[] = [];
  for (const ref of [refOf(doc?.headerImage?.unmarkedImage), refOf(doc?.headerImage?.untitledImage)]) {
    if (ref && ref !== header && !out.includes(ref)) out.push(ref);
  }
  return out;
}

/** AUTO-220: the copy without the mark in a generated answer, or null (also null when it IS the header asset: the mark could not be stamped). */
export function generatedCopyRefOf(outcome: ImageOutcome | undefined): string | null {
  if (outcome?.kind !== 'asset' || outcome.source !== 'ai') return null;
  const ref = outcome.image?.unmarkedImage?.asset?._ref;
  return typeof ref === 'string' && ref && ref !== outcome.image?.asset?._ref ? ref : null;
}

/** The title the post's picture carries, or null (an upload, a product photo, a picture made before the title was drawn in). */
export function titleOnImageOf(doc: BlogImageDoc | null | undefined): string | null {
  const t = doc?.headerImage?.titleOnImage;
  return typeof t === 'string' && t.trim() ? t : null;
}

/** True when the post has a header image of either shape. */
export function hasHeaderImage(doc: BlogImageDoc | null | undefined): boolean {
  return headerImageSignature(doc) !== '';
}

function topicKeywords(doc: BlogImageDoc | null | undefined): string[] {
  const keywords = strings(doc?.aiTopicKeywords);
  const topic = doc?.sourceTopic?.query;
  return keywords.length > 0 ? keywords : typeof topic === 'string' && topic.trim() ? [topic.trim()] : [];
}

/**
 * The request body, from the document in hand. `body` may be passed
 * explicitly (Generate Blog with AI passes the body it has JUST patched,
 * which Sanity has not necessarily stored yet) and defaults to the document's.
 */
export function imageRequestBody(doc: BlogImageDoc | null | undefined, source: 'ai' | 'default', body?: unknown) {
  const postSource = doc?.headerImageSource;
  return {
    title: typeof doc?.title === 'string' ? doc.title : '',
    keywords: topicKeywords(doc),
    skus: collectBlogProductSkus(Array.isArray(body ?? doc?.body) ? ((body ?? doc?.body) as unknown[]) : []),
    rootSlugs: strings(doc?.relatedCategorySlugs),
    slug: typeof doc?.slug?.current === 'string' ? doc.slug.current : '',
    source,
    postSource: typeof postSource === 'string' ? postSource : undefined,
    // AUTO-220: the rung of the ladder the post's picture was drawn on, so this one takes the next.
    previousRung: rungOf(doc?.headerImage?.ladderRung) ?? undefined,
  };
}

/** AUTO-220: Patrick's own instruction, as it is sent (trimmed, capped); empty when the box is empty. */
export function headerInstructionOf(doc: BlogImageDoc | null | undefined): string {
  return cleanInstruction(doc?.headerImageInstruction);
}

/**
 * AUTO-220: why "Change this picture" cannot run on this post, in Patrick's
 * words, or null when it can. A convenience for the button; the server's
 * upload-marker check (lib/blog-automation/header-edit-base.ts) is the rule.
 */
export function changePictureBlocker(doc: BlogImageDoc | null | undefined): string | null {
  const header = headerAssetRefOf(doc);
  if (!header) return 'This post has no header picture to change. Use Make a new picture instead.';
  const unmarked = refOf(doc?.headerImage?.unmarkedImage);
  // A picture the header engine made is 1536 x 864 (the main model) or 1376 x 768 (the backup model).
  if (!unmarked || !/-(?:1536x864|1376x768)-(?:png|jpg)$/.test(header)) {
    return 'Change this picture works only on a picture the AI made with the current header engine. This one is your own upload or an older picture, so it is left as it is. Use Make a new picture instead.';
  }
  if (editCountOf(doc?.headerImage?.editCount) >= MAX_HEADER_EDITS_IN_A_ROW) {
    return `This picture has already been changed ${MAX_HEADER_EDITS_IN_A_ROW} times in a row. Every change redraws the whole picture from the last one, so it gets a little rougher each time. Use Make a new picture instead.`;
  }
  return null;
}

/**
 * AUTO-220: what the two instruction buttons send. `instruction` makes a new
 * picture with Patrick's words and the post's product photos; `edit` sends
 * the current picture's copy without the mark back with his words. The ids
 * only NAME pictures already in the dataset; the server checks both carry
 * the site's upload marker before anything is sent to the AI.
 */
export function instructionRequestBody(doc: BlogImageDoc | null | undefined, mode: 'instruction' | 'edit') {
  const base = imageRequestBody(doc, 'ai');
  return {
    ...base,
    source: mode,
    instruction: headerInstructionOf(doc),
    ...(mode === 'edit'
      ? {
          currentRef: headerAssetRefOf(doc),
          unmarkedRef: refOf(doc?.headerImage?.unmarkedImage),
          editCount: editCountOf(doc?.headerImage?.editCount),
        }
      : {}),
  };
}

/** The patch that puts an outcome onto the post, or null when there is nothing to put (kind 'none'). */
export function patchForOutcome(outcome: ImageOutcome | undefined): { set: Record<string, unknown>; unset: string[] } | null {
  if (outcome?.kind === 'asset' && outcome.image?.asset?._ref) {
    return { set: { headerImage: outcome.image }, unset: ['externalHeaderImage'] };
  }
  if (outcome?.kind === 'url' && outcome.url) {
    return { set: { externalHeaderImage: { url: outcome.url, alt: outcome.alt ?? '' } }, unset: ['headerImage'] };
  }
  return null;
}

/** The daily counter line, when the route reported it. */
export function capOf(outcome: ImageOutcome | undefined): { used: number; cap: number } | undefined {
  const used = outcome?.usage?.capUsed;
  const cap = outcome?.usage?.cap;
  return typeof used === 'number' && typeof cap === 'number' ? { used, cap } : undefined;
}
