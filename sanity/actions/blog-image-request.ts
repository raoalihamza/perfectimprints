/**
 * What the two blog Studio buttons send to /api/sanity/generate-blog-image
 * and what they patch with its answer (AUTO-202). PURE and shared, so the
 * "Generate header image" button and Generate / Regenerate Blog with AI
 * cannot build the request or read the outcome two different ways. No React,
 * no Sanity, no server imports (the Studio bundle takes it).
 */
import { collectBlogProductSkus } from '../../lib/blog/collect-strip-skus';
// Pure (no Sanity, no fs, no network): the one place the reasons are worded.
import { headerImageWhy } from '../../lib/blog-automation/header-image';

export interface BlogImageDoc {
  title?: unknown;
  slug?: { current?: unknown } | null;
  body?: unknown;
  headerImage?: {
    asset?: { _ref?: unknown } | null;
    untitledImage?: { asset?: { _ref?: unknown } | null } | null;
    titleOnImage?: unknown;
    titleTreatment?: unknown;
  } | null;
  externalHeaderImage?: { url?: unknown } | null;
  headerImageSource?: unknown;
  aiTopicKeywords?: unknown;
  sourceTopic?: { query?: unknown } | null;
  relatedCategorySlugs?: unknown;
}

/** The route's answer, the part the buttons read. */
export interface ImageOutcome {
  kind: 'asset' | 'url' | 'none';
  source?: 'ai' | 'library' | 'product';
  image?: {
    _type: 'image';
    asset: { _type: 'reference'; _ref: string };
    alt?: string;
    /** AUTO-209: set when the title was drawn on the picture. */
    titleOnImage?: string;
    untitledImage?: { _type: 'image'; asset: { _type: 'reference'; _ref: string } };
    titleTreatment?: string;
  };
  url?: string;
  alt?: string;
  notes?: string[];
  usage?: { capUsed?: number; cap?: number; attempts?: number };
}

export interface ImageResponse {
  ok?: boolean;
  outcome?: ImageOutcome;
  /** The whole line: "Header image: <what>. <why>". */
  summary?: string;
  /** What the image is, bare: "generated by the AI from the post's product photos". */
  what?: string;
  /** Why, as sentences, each reason said once; empty when there is nothing to say (AUTO-204). */
  why?: string;
  error?: string;
}

/**
 * The reasons behind an outcome, as sentences (AUTO-204). The route's own
 * wording when it sent one; otherwise the notes, sentence by sentence. A
 * dialog prints this ONCE: before AUTO-204 the same explanation appeared
 * inside the summary's brackets and again under a "Note:" heading.
 */
export function imageWhy(data: ImageResponse | undefined): string {
  if (typeof data?.why === 'string') return data.why.trim();
  return headerImageWhy({ notes: data?.outcome?.notes ?? [] });
}

/**
 * What the image is and why, with NO "Header image:" label, for a dialog
 * line that already carries the label ("Filled in: Header image. ...").
 */
export function imageDetail(data: ImageResponse | undefined): string {
  const what = (data?.what ?? '').trim();
  const why = imageWhy(data);
  const first = what ? `${what.charAt(0).toUpperCase()}${what.slice(1)}.` : '';
  return [first, why].filter(Boolean).join(' ');
}

function strings(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((v): v is string => typeof v === 'string' && v.trim().length > 0).map((v) => v.trim()) : [];
}

/** The current header image as one comparable string: the asset ref, the hot link, or empty. */
export function headerImageSignature(doc: BlogImageDoc | null | undefined): string {
  const ref = doc?.headerImage?.asset?._ref;
  if (typeof ref === 'string' && ref) return `asset:${ref}`;
  const url = doc?.externalHeaderImage?.url;
  if (typeof url === 'string' && url.trim()) return `url:${url.trim()}`;
  return '';
}

/** The uploaded header image's asset id, or null (a hot link or no image). AUTO-207: what a replace takes off the post. */
export function headerAssetRefOf(doc: BlogImageDoc | null | undefined): string | null {
  const ref = doc?.headerImage?.asset?._ref;
  return typeof ref === 'string' && ref ? ref : null;
}

/** The asset id of a GENERATED picture in an answer, or null (a library picture, a product photo, nothing). */
export function generatedAssetRefOf(outcome: ImageOutcome | undefined): string | null {
  return outcome?.kind === 'asset' && outcome.source === 'ai' && typeof outcome.image?.asset?._ref === 'string' ? outcome.image.asset._ref : null;
}

/** AUTO-209: the untitled copy kept beside a generated picture on the post, or null. Goes wherever the picture goes. */
export function untitledAssetRefOf(doc: BlogImageDoc | null | undefined): string | null {
  const ref = doc?.headerImage?.untitledImage?.asset?._ref;
  return typeof ref === 'string' && ref ? ref : null;
}

/** AUTO-209: the untitled copy in a generated answer, or null. */
export function generatedUntitledRefOf(outcome: ImageOutcome | undefined): string | null {
  const ref = outcome?.kind === 'asset' && outcome.source === 'ai' ? outcome.image?.untitledImage?.asset?._ref : undefined;
  return typeof ref === 'string' && ref ? ref : null;
}

/** AUTO-209: the title the post's picture carries, or null (an upload, a product photo, an older generated picture). */
export function titleOnImageOf(doc: BlogImageDoc | null | undefined): string | null {
  const t = doc?.headerImage?.titleOnImage;
  return typeof t === 'string' && t.trim() ? t : null;
}

/** True when the post has a header image of either shape. */
export function hasHeaderImage(doc: BlogImageDoc | null | undefined): boolean {
  return headerImageSignature(doc) !== '';
}

/**
 * The request body, from the document in hand. `body` may be passed
 * explicitly (Generate Blog with AI passes the body it has JUST patched,
 * which Sanity has not necessarily stored yet) and defaults to the document's.
 */
export function imageRequestBody(doc: BlogImageDoc | null | undefined, source: 'ai' | 'default', body?: unknown) {
  const keywords = strings(doc?.aiTopicKeywords);
  const topic = doc?.sourceTopic?.query;
  const postSource = doc?.headerImageSource;
  const treatment = doc?.headerImage?.titleTreatment;
  return {
    title: typeof doc?.title === 'string' ? doc.title : '',
    keywords: keywords.length > 0 ? keywords : typeof topic === 'string' && topic.trim() ? [topic.trim()] : [],
    skus: collectBlogProductSkus(Array.isArray(body ?? doc?.body) ? ((body ?? doc?.body) as unknown[]) : []),
    rootSlugs: strings(doc?.relatedCategorySlugs),
    slug: typeof doc?.slug?.current === 'string' ? doc.slug.current : '',
    source,
    postSource: typeof postSource === 'string' ? postSource : undefined,
    // AUTO-210: the look the post's picture has now, so a regenerate takes the next one.
    previousTreatment: typeof treatment === 'string' && treatment ? treatment : undefined,
  };
}

/**
 * AUTO-209: what "Redraw title on header image" sends: the post's current
 * title, the untitled copy's id, the stored placement, the slug and the topic
 * (for the alt text). No SKUs, no URL: the route reads the asset itself and
 * refuses anything that is not a picture the site generated.
 */
export function retitleRequestBody(doc: BlogImageDoc | null | undefined) {
  const keywords = strings(doc?.aiTopicKeywords);
  const topic = doc?.sourceTopic?.query;
  return {
    source: 'retitle' as const,
    title: typeof doc?.title === 'string' ? doc.title : '',
    untitledRef: untitledAssetRefOf(doc),
    treatment: typeof doc?.headerImage?.titleTreatment === 'string' ? doc.headerImage.titleTreatment : null,
    slug: typeof doc?.slug?.current === 'string' ? doc.slug.current : '',
    keywords: keywords.length > 0 ? keywords : typeof topic === 'string' && topic.trim() ? [topic.trim()] : [],
  };
}

/** The patch that puts an outcome onto the post, or null when there is nothing to put (kind 'none'). */
export function patchForOutcome(outcome: ImageOutcome | undefined): { set: Record<string, unknown>; unset: string[] } | null {
  if (outcome?.kind === 'asset' && outcome.image?.asset?._ref) {
    return { set: { headerImage: outcome.image }, unset: ['externalHeaderImage'] };
  }
  if (outcome?.kind === 'url' && outcome.url) {
    return { set: { externalHeaderImage: { url: outcome.url, alt: outcome.alt ?? '' } }, unset: ['headerImage'] };
  }
  return null;
}

/** The daily counter line, when the route reported it. */
export function capOf(outcome: ImageOutcome | undefined): { used: number; cap: number } | undefined {
  const used = outcome?.usage?.capUsed;
  const cap = outcome?.usage?.cap;
  return typeof used === 'number' && typeof cap === 'number' ? { used, cap } : undefined;
}
