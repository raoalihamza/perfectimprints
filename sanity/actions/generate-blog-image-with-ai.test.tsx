// @vitest-environment jsdom
/**
 * AUTO-202: the "Generate header image" button driven for real (React 19
 * `act`, the Sanity document operation and the nonce fetch mocked).
 *
 *   - With no header image it runs at once and patches the picture.
 *   - With an image it asks first; cancelling changes nothing; confirming
 *     replaces the picture.
 *   - When the AI made nothing and the chain fell back to a library picture
 *     or a product photo, an image already on the post is KEPT.
 *   - An image uploaded during the wait is kept.
 *   - The cap's refusal is shown in its own words.
 *   - It shares the running lock with the writing buttons.
 *
 * AUTO-204: the notice says each thing ONCE. Before it, the refusal
 * explanation was printed inside the summary's brackets and again, word for
 * word, under a "Note:" heading. The mocks below are built with the server's
 * own summary functions, so the dialog is tested against the real wording.
 */
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { renderToStaticMarkup } from 'react-dom/server';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({
  execute: vi.fn(),
  onComplete: vi.fn(),
  authFetch: vi.fn(),
  afterReplace: vi.fn(),
  unused: vi.fn(),
}));

vi.mock('sanity', () => ({
  useDocumentOperation: () => ({ patch: { execute: mocks.execute } }),
}));
vi.mock('../components/useGenerateAuthFetch', () => ({
  useGenerateAuthFetch: () => mocks.authFetch,
}));
// AUTO-207: the Studio half of "a replaced generated picture goes"; the rule itself is tested in discard-header-image.test.ts.
vi.mock('../components/useHeaderAssetDiscard', () => ({
  useHeaderAssetDiscard: () => ({ afterReplace: mocks.afterReplace, unused: mocks.unused }),
}));

// eslint-disable-next-line import/first
import { generateBlogImageWithAi } from './generate-blog-image-with-ai';
// eslint-disable-next-line import/first
import { setBlogActionRunning } from './blog-running';
// eslint-disable-next-line import/first
import { headerImageSummary, headerImageWhat, headerImageWhy, type HeaderImageOutcome } from '../../lib/blog-automation/header-image';

/** The route's answer for an outcome, worded by the server's own functions. */
function routeAnswer(outcome: HeaderImageOutcome) {
  return { ok: true, source: 'ai', outcome, summary: headerImageSummary(outcome), what: headerImageWhat(outcome), why: headerImageWhy(outcome) };
}
/** Ali's case: both generated pictures refused, the library empty, the first product photo used instead. */
const REFUSED_TWICE: HeaderImageOutcome = {
  kind: 'url',
  source: 'product',
  url: 'https://imgsirv.geiger.com/master/106415/web/106415_91A_1.jpg?format=webp&thumbnail=275&w=275&h=275',
  alt: "Cook's Choice One-Cup Measuring Cup",
  notes: [
    'both generated pictures were refused, so neither was used: the first showed words on a sign, a label, a cover or a screen ("The Joy of Baking" on a cookbook cover); the second showed a logo or brand mark (Apple logo on laptop)',
    'the header image library is empty',
  ],
};
const count = (html: string, needle: string) => html.split(needle).length - 1;
const htmlOf = (dialog: unknown) => renderToStaticMarkup((dialog as { content: React.ReactElement }).content);

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

type Dialog = { type?: string; header?: string; onConfirm?: () => void; onCancel?: () => void; onClose?: () => void; content?: unknown } | false | undefined;
type Description = { label?: string; onHandle?: () => void; disabled?: boolean; dialog?: Dialog } | null;
let action: Description = null;

type Props = Parameters<typeof generateBlogImageWithAi>[0];
function Harness(props: Props) {
  action = generateBlogImageWithAi(props) as Description;
  return null;
}

const generatedImage = { _type: 'image', asset: { _type: 'reference', _ref: 'image-generated-1376x768-jpg' }, alt: 'alt' };
const aiResponse = { ok: true, source: 'ai', outcome: { kind: 'asset', source: 'ai', image: generatedImage, notes: [], usage: { capUsed: 2, cap: 20 } }, summary: 'Header image: generated by the AI.' };
const productFallback = {
  ok: true,
  source: 'ai',
  outcome: { kind: 'url', source: 'product', url: 'https://imgsirv.geiger.com/master/101003/web/101003_1.jpg?w=275', alt: 'Tote', notes: ['the image model failed: 503'] },
  summary: 'Header image: the first product photo.',
};
const UPLOADED = { headerImage: { _type: 'image', asset: { _type: 'reference', _ref: 'image-uploaded-2000x1125-jpg' } } };

let root: Root;
let container: HTMLDivElement;

function propsFor(draft: Record<string, unknown>): Props {
  return {
    id: 'post-1',
    type: 'blogPost',
    draft: { _id: 'drafts.post-1', _type: 'blogPost', ...draft },
    published: null,
    onComplete: mocks.onComplete,
  } as unknown as Props;
}
async function render(props: Props) {
  await act(async () => {
    root.render(<Harness {...props} />);
  });
}
function allSets(): Record<string, unknown>[] {
  return mocks.execute.mock.calls.flatMap((call) => (call[0] as { set?: Record<string, unknown> }[]).filter((p) => p.set).map((p) => p.set as Record<string, unknown>));
}
function allUnsets(): string[] {
  return mocks.execute.mock.calls.flatMap((call) => (call[0] as { unset?: string[] }[]).filter((p) => p.unset).flatMap((p) => p.unset as string[]));
}

beforeEach(() => {
  mocks.execute.mockReset();
  mocks.onComplete.mockReset();
  mocks.authFetch.mockReset();
  mocks.afterReplace.mockReset();
  mocks.unused.mockReset();
  mocks.authFetch.mockResolvedValue({ ok: true, json: async () => aiResponse });
  setBlogActionRunning('post-1', false);
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});
afterEach(async () => {
  await act(async () => root.unmount());
  container.remove();
});

const base = { title: 'Custom Tote Bags', slug: { current: 'custom-tote-bags' }, aiTopicKeywords: ['custom tote bags'], relatedCategorySlugs: ['tote-bags'] };

describe('Generate header image', () => {
  it('with no image: runs at once, sends the title, keywords, strip SKUs and roots with source "ai", and patches the picture', async () => {
    await render(propsFor({ ...base, body: [{ _type: 'blogProducts', _key: 's', products: [{ _type: 'blogProduct', sku: '501003' }] }] }));
    expect(action!.label).toBe('Generate header image');
    await act(async () => {
      action!.onHandle!();
    });
    expect(mocks.authFetch).toHaveBeenCalledTimes(1);
    const [url, init] = mocks.authFetch.mock.calls[0] as [string, RequestInit];
    expect(url).toBe('/api/sanity/generate-blog-image');
    expect(JSON.parse(init.body as string)).toEqual({ title: 'Custom Tote Bags', keywords: ['custom tote bags'], skus: ['501003'], rootSlugs: ['tote-bags'], slug: 'custom-tote-bags', source: 'ai', postSource: undefined });
    expect(allSets()).toEqual([{ headerImage: generatedImage }]);
    expect(allUnsets()).toEqual(['externalHeaderImage']);
    const dialog = action!.dialog as Exclude<Dialog, false | undefined>;
    expect(dialog.header).toBe('Header image updated');
  });

  it('with an image: asks first; cancelling sends nothing; confirming replaces it', async () => {
    await render(propsFor({ ...base, ...UPLOADED }));
    expect(action!.label).toBe('Generate another header image');
    await act(async () => {
      action!.onHandle!();
    });
    let dialog = action!.dialog as Exclude<Dialog, false | undefined>;
    expect(dialog.type).toBe('confirm');
    expect(mocks.authFetch).not.toHaveBeenCalled();
    await act(async () => {
      dialog.onCancel!();
    });
    expect(mocks.authFetch).not.toHaveBeenCalled();
    expect(mocks.execute).not.toHaveBeenCalled();

    await act(async () => {
      action!.onHandle!();
    });
    dialog = action!.dialog as Exclude<Dialog, false | undefined>;
    await act(async () => {
      dialog.onConfirm!();
    });
    expect(mocks.authFetch).toHaveBeenCalledTimes(1);
    expect(allSets()).toEqual([{ headerImage: generatedImage }]);
    // AUTO-207: the picture it replaced is handed to the guarded rule (which keeps an upload like this one); nothing was unused.
    expect(mocks.afterReplace.mock.calls).toEqual([['image-uploaded-2000x1125-jpg']]);
    expect(mocks.unused).not.toHaveBeenCalled();
  });

  it('AUTO-207: with no image before, nothing is handed to the removal rule', async () => {
    await render(propsFor(base));
    await act(async () => {
      action!.onHandle!();
    });
    expect(allSets()).toEqual([{ headerImage: generatedImage }]);
    expect(mocks.afterReplace).not.toHaveBeenCalled();
    expect(mocks.unused).not.toHaveBeenCalled();
  });

  it('a fallback picture never replaces an image already on the post; it may fill an empty one', async () => {
    mocks.authFetch.mockResolvedValue({ ok: true, json: async () => productFallback });
    await render(propsFor({ ...base, ...UPLOADED }));
    await act(async () => {
      action!.onHandle!();
    });
    await act(async () => {
      (action!.dialog as { onConfirm: () => void }).onConfirm();
    });
    expect(mocks.execute).not.toHaveBeenCalled();
    expect((action!.dialog as { header?: string }).header).toBe('Your image was kept');

    mocks.execute.mockReset();
    await act(async () => root.unmount());
    root = createRoot(container);
    await render(propsFor(base));
    await act(async () => {
      action!.onHandle!();
    });
    expect(allSets()).toEqual([{ externalHeaderImage: { url: productFallback.outcome.url, alt: 'Tote' } }]);
    expect(allUnsets()).toEqual(['headerImage']);
  });

  it('an image uploaded during the wait is kept', async () => {
    let resolve!: (v: unknown) => void;
    mocks.authFetch.mockReturnValue(new Promise((r) => (resolve = r)));
    await render(propsFor(base));
    await act(async () => {
      action!.onHandle!();
    });
    await render(propsFor({ ...base, ...UPLOADED }));
    await act(async () => {
      resolve({ ok: true, json: async () => aiResponse });
    });
    expect(mocks.execute).not.toHaveBeenCalled();
    expect((action!.dialog as { header?: string }).header).toBe('Your image was kept');
    // AUTO-207: the picture made for nothing is removed rather than left in the media library.
    expect(mocks.unused.mock.calls).toEqual([['image-generated-1376x768-jpg']]);
    expect(mocks.afterReplace).not.toHaveBeenCalled();
  });

  it("the cap's refusal is shown in its own words and nothing is changed", async () => {
    mocks.authFetch.mockResolvedValue({
      ok: true,
      json: async () => ({ ok: true, source: 'ai', outcome: { kind: 'none', notes: ['The daily limit of 20 generated header images has been reached, so no image was made. The limit resets at midnight UTC (evening in Florida).'] }, summary: 'Header image: none.' }),
    });
    await render(propsFor(base));
    await act(async () => {
      action!.onHandle!();
    });
    expect(mocks.execute).not.toHaveBeenCalled();
    const dialog = action!.dialog as { header?: string; content?: React.ReactElement };
    expect(dialog.header).toBe('No header image was made');
    expect(renderToStaticMarkup(dialog.content as React.ReactElement)).toContain('The daily limit of 20 generated header images has been reached');
  });

  it('is disabled while a writing button runs on the same document, and without a title', async () => {
    await render(propsFor(base));
    expect(action!.disabled).toBe(false);
    setBlogActionRunning('post-1', true);
    await render(propsFor(base));
    expect(action!.disabled).toBe(true);
    setBlogActionRunning('post-1', false);
    await render(propsFor({ ...base, title: '' }));
    expect(action!.disabled).toBe(true);
  });
});

describe('the notice says each thing once (AUTO-204)', () => {
  it("Ali's case: both pictures refused and a product photo used; the explanation is printed ONCE, with no Note heading, and the dialog says it is a stand-in", async () => {
    mocks.authFetch.mockResolvedValue({ ok: true, json: async () => routeAnswer(REFUSED_TWICE) });
    await render(propsFor(base));
    await act(async () => {
      action!.onHandle!();
    });
    const dialog = action!.dialog as { header?: string };
    expect(dialog.header).toBe('A stand-in picture was used');
    const html = htmlOf(dialog);
    expect(count(html, 'Both generated pictures were refused')).toBe(1);
    expect(count(html, 'The Joy of Baking')).toBe(1);
    expect(count(html, 'Apple logo on laptop')).toBe(1);
    expect(count(html, 'The header image library is empty')).toBe(1);
    expect(html).not.toContain('Note:');
    expect(html).toContain('This is a stand-in, not a picture made for this post.');
    // The advice about an AI picture is not shown for a picture the AI did not make.
    expect(html).not.toContain('Look at it before you publish');
    // And it was put on the post, as the hot link.
    expect(allSets()).toEqual([{ externalHeaderImage: { url: REFUSED_TWICE.kind === 'url' ? REFUSED_TWICE.url : '', alt: "Cook's Choice One-Cup Measuring Cup" } }]);
  });

  it('an AI picture that replaced a refused first attempt: the reason is said once, with the advice to look at it', async () => {
    const outcome: HeaderImageOutcome = {
      kind: 'asset',
      source: 'ai',
      image: { _type: 'image', asset: { _type: 'reference', _ref: 'image-generated-1376x768-jpg' }, alt: 'alt' },
      notes: ['the first picture showed a logo or brand mark (Apple logo on laptop) and was replaced'],
      usage: { model: 'm', imageTokens: 2240, promptTokens: 1, elapsedMs: 1, attempts: 2, capUsed: 4, cap: 20 },
    };
    mocks.authFetch.mockResolvedValue({ ok: true, json: async () => routeAnswer(outcome) });
    await render(propsFor(base));
    await act(async () => {
      action!.onHandle!();
    });
    const dialog = action!.dialog as { header?: string };
    expect(dialog.header).toBe('Header image updated');
    const html = htmlOf(dialog);
    expect(count(html, 'The first picture showed a logo or brand mark (Apple logo on laptop) and was replaced.')).toBe(1);
    expect(count(html, 'Look at it before you publish')).toBe(1);
    expect(html).toContain('logos, brand names and stray words');
    expect(html).not.toContain('Note:');
    expect(html).not.toContain('stand-in');
    expect(html).toContain('4 of 20 generated header images used today.');
  });

  it('an image kept because the AI made nothing: the reason is said once, after the sentence that says it was kept', async () => {
    mocks.authFetch.mockResolvedValue({ ok: true, json: async () => routeAnswer(REFUSED_TWICE) });
    await render(propsFor({ ...base, ...UPLOADED }));
    await act(async () => {
      action!.onHandle!();
    });
    await act(async () => {
      (action!.dialog as { onConfirm: () => void }).onConfirm();
    });
    expect(mocks.execute).not.toHaveBeenCalled();
    const dialog = action!.dialog as { header?: string };
    expect(dialog.header).toBe('Your image was kept');
    const html = htmlOf(dialog);
    expect(count(html, 'your current header image was kept')).toBe(1);
    expect(count(html, 'Both generated pictures were refused')).toBe(1);
    // The stand-in the chain offered is not described as if it were on the post.
    expect(html).not.toContain("the post&#x27;s first product photo");
    expect(html).not.toContain('Note:');
  });

  it('no picture at all: the reasons are said once in the error, each as a sentence', async () => {
    const outcome: HeaderImageOutcome = { kind: 'none', notes: ['the image model failed: Image request failed (503).', 'the header image library is empty', 'the post has no product photo to fall back on'] };
    mocks.authFetch.mockResolvedValue({ ok: true, json: async () => routeAnswer(outcome) });
    await render(propsFor(base));
    await act(async () => {
      action!.onHandle!();
    });
    const dialog = action!.dialog as { header?: string };
    expect(dialog.header).toBe('No header image was made');
    const html = htmlOf(dialog);
    expect(html).toContain(
      'No picture could be made. The image model failed: Image request failed (503). The header image library is empty. The post has no product photo to fall back on. Nothing on the post was changed.',
    );
    expect(count(html, 'The header image library is empty')).toBe(1);
  });

  it('an answer from a server that sends no "why" still says the reasons once, from the notes', async () => {
    const { why: _why, what: _what, ...older } = routeAnswer(REFUSED_TWICE);
    void _why;
    void _what;
    mocks.authFetch.mockResolvedValue({ ok: true, json: async () => older });
    await render(propsFor({ ...base, ...UPLOADED }));
    await act(async () => {
      action!.onHandle!();
    });
    await act(async () => {
      (action!.dialog as { onConfirm: () => void }).onConfirm();
    });
    expect(count(htmlOf(action!.dialog), 'Both generated pictures were refused')).toBe(1);
  });
});
